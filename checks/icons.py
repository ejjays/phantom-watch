#!/usr/bin/env python3
"""Regenerate web/web/icons.js from android drawables, same glyphs both platforms."""
import re, pathlib

WANT = ["ic_back", "ic_chevron_down", "ic_cc_on", "ic_cc_off", "ic_settings",
        "ic_volume_on", "ic_volume_off", "ic_fullscreen", "ic_fullscreen_exit",
        "ic_play", "ic_pause", "ic_lock", "ic_unlock", "ic_seek_chevron",
        "ic_quality", "ic_speed", "ic_check", "ic_chevron_right", "ic_episodes",
        "ic_skip_next_filled", "ic_revert", "ic_dubs", "ic_brightness"]
SRC = pathlib.Path("app/src/main/res/drawable")
OUT = pathlib.Path("web/web/icons.js")

def attrs(block, name):
    m = re.search(r'android:%s="([^"]*)"' % name, block)
    return m.group(1) if m else None

def one(name):
    s = (SRC / (name + ".xml")).read_text()
    paths = []
    for p in re.findall(r"<path\b([^>]*)/>", s):
        d = attrs(p, "pathData")
        if not d:
            continue
        fill = attrs(p, "fillColor") or "none"
        stroke = attrs(p, "strokeColor") or "none"
        a = ['d="%s"' % d, 'fill="%s"' % fill]
        if attrs(p, "fillType"):
            a.append('fill-rule="%s"' % attrs(p, "fillType").replace("evenOdd", "evenodd"))
        if stroke != "none":
            a += ['stroke="%s"' % stroke, 'stroke-width="%s"' % (attrs(p, "strokeWidth") or "1"),
                  'stroke-linecap="%s"' % (attrs(p, "strokeLineCap") or "butt"),
                  'stroke-linejoin="%s"' % (attrs(p, "strokeLineJoin") or "miter")]
        paths.append("<path %s/>" % " ".join(a))
    return "".join(paths)


def viewport(s):
    w = re.search(r'android:viewportWidth="([^"]*)"', s)
    h = re.search(r'android:viewportHeight="([^"]*)"', s)
    return (w.group(1) if w else "24") + " " + (h.group(1) if h else "24")


# layer vector group shifts, skipping draws glyph off centre
def shift(s):
    g = re.search(r"<group\b([^>]*)>", s)
    if not g:
        return None
    x = attrs(g.group(1), "translateX") or "0"
    y = attrs(g.group(1), "translateY") or "0"
    return None if x == "0" and y == "0" else "translate(%s,%s)" % (x, y)

lines = ["// Generated by checks/icons.py from app/src/main/res/drawable — do not edit.",
         "window.PW_ICONS = {"]
for n in WANT:
    src = (SRC / (n + ".xml")).read_text()
    body = one(n)
    g = shift(src)
    if g:
        body = '<g transform="%s">%s</g>' % (g, body)
    lines.append('  %s: \'<svg viewBox="0 0 %s" width="100%%" height="100%%">%s</svg>\',' % (n[3:], viewport(src), body))
lines.append("};")
OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT, OUT.stat().st_size, "bytes")
