#!/usr/bin/env python3
"""Regenerate spike/web/icons.js from app/src/main/res/drawable so the web player
uses the exact same glyphs as the phone. Run from the repo root."""
import re, pathlib

WANT = ["ic_back", "ic_chevron_down", "ic_cc_on", "ic_cc_off", "ic_settings",
        "ic_volume_on", "ic_volume_off", "ic_fullscreen", "ic_fullscreen_exit",
        "ic_play", "ic_pause", "ic_lock", "ic_unlock", "ic_seek_chevron"]
SRC = pathlib.Path("app/src/main/res/drawable")
OUT = pathlib.Path("spike/web/icons.js")

def attrs(block, name):
    m = re.search(r'android:%s="([^"]*)"' % name, block)
    return m.group(1) if m else None

def one(name):
    s = (SRC / (name + ".xml")).read_text()
    paths = []
    for p in re.findall(r"<path\b([^>]*)/>", s):
        d = attrs(p, "pathData")
        if not d:
            continue
        fill = attrs(p, "fillColor") or "none"
        stroke = attrs(p, "strokeColor") or "none"
        a = ['d="%s"' % d, 'fill="%s"' % fill]
        if attrs(p, "fillType"):
            a.append('fill-rule="%s"' % attrs(p, "fillType").replace("evenOdd", "evenodd"))
        if stroke != "none":
            a += ['stroke="%s"' % stroke, 'stroke-width="%s"' % (attrs(p, "strokeWidth") or "1"),
                  'stroke-linecap="%s"' % (attrs(p, "strokeLineCap") or "butt"),
                  'stroke-linejoin="%s"' % (attrs(p, "strokeLineJoin") or "miter")]
        paths.append("<path %s/>" % " ".join(a))
    return "".join(paths)

lines = ["// Generated by checks/icons.py from app/src/main/res/drawable — do not edit.",
         "window.PW_ICONS = {"]
for n in WANT:
    lines.append('  %s: \'<svg viewBox="0 0 24 24" width="100%%" height="100%%">%s</svg>\',' % (n[3:], one(n)))
lines.append("};")
OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT, OUT.stat().st_size, "bytes")
